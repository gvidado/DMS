import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {readFile} from 'node:fs/promises';
import {join} from 'node:path';

const input=JSON.parse(await readFile(process.argv[2],'utf8'));
const require=createRequire(import.meta.url);
const {chromium}=require(process.env.DMS_BROWSER_NODE_MODULES?join(process.env.DMS_BROWSER_NODE_MODULES,'playwright'):'playwright');
const browser=await chromium.launch({headless:true,channel:'msedge'});
try{
  const page=await browser.newPage(),errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(input.base+'/?section=sequences&view=sequence-config');
  await page.locator('#login-username').fill('groupqa');
  await page.locator('#login-password').fill(input.password);
  await page.locator('#login-submit').click();
  const configSelect=page.locator('#sequence-config-select');
  const group=page.locator('#sequence-preview-group');
  const groupLabel=async id=>configSelect.locator('option[value="'+id+'"]').evaluate(option=>option.parentElement.label||'');
  await configSelect.locator('option[value="'+input.oldId+'"]').waitFor({state:'attached'});
  await page.locator('#sequence-file').setInputFiles(input.workbook);
  await page.locator('#sequence-import-group').fill('批次一');
  await page.locator('#sequence-read').click();
  const sheets=page.locator('.sequence-sheet-line');
  await sheets.nth(2).waitFor();
  const first=await sheets.nth(0).locator('input').inputValue(),second=await sheets.nth(1).locator('input').inputValue();
  assert.equal(await group.inputValue(),'批次一');
  await sheets.nth(2).locator('input').uncheck();
  await sheets.nth(2).locator('button').click();
  await group.fill('不保存该组');
  await sheets.nth(1).locator('button').click();
  await group.fill('专项二');
  await page.locator('#sequence-preview-name').fill('乙序列');
  await page.locator('#sequence-recheck').click();
  await page.waitForFunction(()=>!document.querySelector('#sequence-apply').disabled);
  assert.equal(await group.inputValue(),'专项二');
  await page.locator('#sequence-apply').click();
  await configSelect.locator('option[value="'+second+'"]').waitFor({state:'attached'});
  assert.equal(await groupLabel(first),'批次一');
  assert.equal(await groupLabel(second),'专项二');
  assert.equal(await configSelect.locator('option').count(),4);
  assert.equal(await groupLabel(input.oldId),'（未分组）');
  await configSelect.selectOption(input.oldId);
  await page.waitForFunction(()=>document.querySelector('#sequence-preview-name').value==='旧版序列');
  assert.equal(await group.inputValue(),'');
  assert.equal(await page.locator('#sequence-group-names option[value="专项二"]').count(),1);
  await group.fill('专项二');
  await page.locator('#sequence-save-edits').click();
  await page.waitForFunction(id=>document.querySelector('#sequence-config-select option[value="'+id+'"]').parentElement.label==='专项二',input.oldId);
  await group.fill('');
  await page.locator('#sequence-save-edits').click();
  await page.waitForFunction(id=>document.querySelector('#sequence-config-select option[value="'+id+'"]').parentElement.label==='（未分组）',input.oldId);
  await page.locator('#sequence-go-run').click();
  const runSelect=page.locator('#sequence-run-select');
  await runSelect.locator('optgroup[label="批次一"]').waitFor({state:'attached'});
  assert.equal(await runSelect.locator('optgroup[label="专项二"] option').textContent(),'XLP0003 · 乙序列');
  assert.equal(await runSelect.locator('optgroup[label="（未分组）"] option').textContent(),'XLP0001 · 旧版序列');
  assert.deepEqual(errors,[]);
  console.log('PASS Excel batch groups, per-sequence overrides, unselected sheets, editing and grouped launch');
}finally{await browser.close();}
